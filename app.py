    if key == "normes_referentiels":
        rows = [{"Code": f"NR-{i:02d}", "Norme / référentiel": code, "Objet": obj,
                 "Version / édition": version, "Applicabilité": "À examiner",
                 "Statut de vérification": "À vérifier"}
                for i, (code, obj, version) in enumerate(NORMES_REFERENTIELS, 1)]
