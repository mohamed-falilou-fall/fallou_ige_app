def _empty_df(key):
    return pd.DataFrame(columns=TABLE_SCHEMAS[key])


def _initial_df(key):
    if key == "familles_juridiques":
        rows = [{"Code famille": f"FJ-{i:02d}", "Famille juridique et réglementaire": name,
                 "Statut": "À documenter"} for i, name in enumerate(FAMILLES_JURIDIQUES, 1)]
